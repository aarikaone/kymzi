#!/usr/bin/env node
// Offline inventory and publishing only. This script never calls a generation API.
import {createHash} from 'node:crypto';
import {existsSync,readFileSync,mkdirSync,writeFileSync,linkSync,copyFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {imageSize} from 'image-size';

const ROOT=fileURLToPath(new URL('..',import.meta.url));
const check=process.argv.includes('--check');
const catalogueFile=path.join(ROOT,'content/world-catalogue/catalogue.json');
const catalogue=JSON.parse(readFileSync(catalogueFile,'utf8'));
const approvedFile=path.join(ROOT,'content/world-art/approved.json');
const approved=JSON.parse(readFileSync(approvedFile,'utf8'));
const style=readFileSync(path.join(ROOT,'content/world-art/style.txt'),'utf8').trim();
const entries=[],jobs=[],ready={},seen=new Set(),paths=new Set();
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
function prompt(kind,city,place){
 const name=kind==='city'?`${city.city}, ${city.region}, ${city.country}`:`${place.name}, in or near ${city.city}, ${city.country}`;
 const subject=kind==='city'?`A city travel cover featuring ${city.places.find(p=>/Palace|Castle|Landmark|Architecture|Bridge|Garden/.test(p.kind))?.name??city.places[0].name} and its local setting.`:`Subject: ${place.name}. Place type: ${place.kind}. Catalogue description: ${place.description}.`;
 return `${style}\nDestination: ${name}. ${subject}\nCreate one continuous landscape illustration, no collage or panels. No title, caption, labels, logos or watermark. Keep the subject readable in a small mobile card. Use established visual details where known; when appearance is uncertain, use a representative illustration of the sourced place type rather than inventing distinctive architecture. This is guide artwork, not a documentary photograph.`;
}
function add(kind,city,place){
 const id=kind==='city'?city.id:place.id,key=`${kind}/${id}`;
 if(seen.has(key))throw new Error(`Duplicate asset: ${key}`);seen.add(key);
 const legacy=kind==='city'?city.places.find(p=>p.source!=='Wikidata'):place.source!=='Wikidata'?place:null;
 const relativePath=kind==='city'?`cities/${city.geonameId}.jpg`:`places/${place.id}.jpg`;
 if(paths.has(relativePath))throw new Error(`Duplicate output: ${relativePath}`);paths.add(relativePath);
 const entry={key,kind,id,cityId:city.id,name:kind==='city'?city.city:place.name,country:city.country,sourceUrl:kind==='city'?city.citySourceUrl:place.sourceUrl,status:'missing',relativePath};
 if(legacy){
  const atlas=Math.floor(catalogue.cities.filter(c=>!c.id.startsWith('city:')).findIndex(c=>c.id===city.id)/2)+1;
  for(const location of [`packages/assets/attractions/atlas-${String(atlas).padStart(2,'0')}.png`,`apps/web/public/attractions/atlas-${String(atlas).padStart(2,'0')}.webp`])if(!existsSync(path.join(ROOT,location)))throw new Error(`Missing existing artwork: ${location}`);
  entry.status='existing';entry.legacyArtworkId=legacy.id;
 }else{
  const record=approved[key],source=path.join(ROOT,'packages/assets/world/v1',relativePath);
  if(record){
   if(record.relativePath!==relativePath||record.reviewed!==true)throw new Error(`Unreviewed or mismatched art: ${key}`);
   const bytes=readFileSync(source),size=imageSize(bytes);
   if(sha(bytes)!==record.sha256||!size.width||!size.height||size.width<640||size.height<480)throw new Error(`Invalid generated image: ${key}`);
   entry.status='generated';entry.sha256=record.sha256;
   ready[key]={path:relativePath,width:size.width,height:size.height};
  }else jobs.push({id:key,kind,name:entry.name,city:city.city,country:city.country,sourceUrl:entry.sourceUrl,output:relativePath,prompt:prompt(kind,city,place)});
 }
 entries.push(entry);
}
for(const city of catalogue.cities){add('city',city);for(const place of city.places)add('place',city,place);}
for(const key of Object.keys(approved))if(!ready[key])throw new Error(`Approved image has no matching catalogue slot: ${key}`);
const counts={cities:catalogue.cities.length,places:catalogue.cities.reduce((n,c)=>n+c.places.length,0),totalSlots:entries.length,existing:entries.filter(e=>e.status==='existing').length,generated:Object.keys(ready).length,missing:jobs.length};
if(counts.totalSlots!==counts.existing+counts.generated+counts.missing)throw new Error('Image coverage totals do not balance.');
const content=path.join(ROOT,'content/world-art'),runtime=path.join(ROOT,'packages/core/src/catalogue/world-art-data.ts');
const index=`// Generated by scripts/prepare-world-art.mjs; only reviewed, verified bitmap assets.\nexport const GENERATED_WORLD_ART:Record<string,{path:string;width:number;height:number}> = ${JSON.stringify(ready)};\n`;
const manifest={version:1,catalogueSha256:sha(readFileSync(catalogueFile)),...counts,entries};
if(check){
 const saved=JSON.parse(readFileSync(path.join(content,'manifest.json'),'utf8'));
 if(JSON.stringify(saved)!==JSON.stringify(manifest)||readFileSync(runtime,'utf8')!==index)throw new Error('Artwork inventory is stale. Run npm run art:prepare.');
 console.log(JSON.stringify({verified:true,...counts}));
}else{
 mkdirSync(content,{recursive:true});writeFileSync(path.join(content,'manifest.json'),JSON.stringify(manifest));writeFileSync(path.join(content,'coverage.json'),JSON.stringify({version:1,catalogueSha256:manifest.catalogueSha256,...counts},null,2)+'\n');writeFileSync(runtime,index);
 const folder=path.join(ROOT,'artifacts/world-art');mkdirSync(folder,{recursive:true});writeFileSync(path.join(folder,'pending-prompts.jsonl'),jobs.map(j=>JSON.stringify(j)).join('\n')+'\n');
 // Bitmap sources are published only by cloud:prepare; the apps never bundle them.
 console.log(JSON.stringify({...counts,prompts:'artifacts/world-art/pending-prompts.jsonl'}));
}
